import { useState } from 'react';
import { Database, RefreshCw, Loader2, CheckCircle2, AlertTriangle, HardDrive, Server } from 'lucide-react';
import { sqlApi, type DatasetIngestResult } from '../services/sqlApi';
import { useAsyncData } from '../hooks/useAsyncData';
import type { DatasetInfo } from '../types';

function Stat({ label, value, sub }: { label: string; value: string | number; sub?: string }) {
  return (
    <div className="card p-4">
      <p className="label-caps">{label}</p>
      <p className="mt-1 text-2xl font-extrabold text-slate-900">{value}</p>
      {sub && <p className="mt-0.5 text-[11px] text-slate-400">{sub}</p>}
    </div>
  );
}

function fmtDate(v: string | null | undefined): string {
  if (!v) return '—';
  const d = new Date(v);
  return Number.isNaN(d.getTime()) ? v : d.toLocaleString('en-IN');
}

export function Dataset() {
  const { data, loading, error, refetch } = useAsyncData<DatasetInfo>(() => sqlApi.datasetInfo(), []);
  const [ingesting, setIngesting] = useState(false);
  const [result, setResult] = useState<DatasetIngestResult | null>(null);
  const [ingestError, setIngestError] = useState<string | null>(null);

  const runIngest = async () => {
    setIngesting(true);
    setResult(null);
    setIngestError(null);
    try {
      const res = await sqlApi.datasetIngest();
      setResult(res);
      refetch();
    } catch (e) {
      setIngestError((e as Error).message);
    } finally {
      setIngesting(false);
    }
  };

  return (
    <div className="mx-auto max-w-5xl px-4 pb-28 pt-5">
      <div className="fade-up flex flex-wrap items-end justify-between gap-3">
        <div>
          <p className="text-xs font-bold uppercase tracking-[0.18em] text-brand-600">Data Provenance</p>
          <h1 className="mt-1 flex items-center gap-2 text-2xl font-extrabold tracking-tight text-slate-900">
            <Database className="h-6 w-6 text-brand-600" /> Dataset information
          </h1>
          <p className="mt-0.5 text-sm text-slate-500">
            Everything served by this app is read from the local SQL dataset.
          </p>
        </div>
        <button onClick={runIngest} disabled={ingesting} className="btn-primary">
          {ingesting ? <Loader2 className="h-4 w-4 animate-spin" /> : <RefreshCw className="h-4 w-4" />}
          {ingesting ? 'Ingesting…' : 'Re-run ingest'}
        </button>
      </div>

      <p className="mt-4 flex items-start gap-2 rounded-2xl bg-brand-50 px-4 py-3 text-xs text-brand-800 ring-1 ring-brand-100">
        <Server className="mt-0.5 h-4 w-4 shrink-0" />
        Data flows: <b className="font-extrabold">Frontend → MAUSAM backend → SQLite dataset</b>. Live IMD ingestion is
        optional and OFF by default; when disabled, rows are generated by the deterministic simulator and clearly
        marked <code className="rounded bg-white px-1">is_demo</code>.
      </p>

      {result && (
        <p className="mt-4 flex items-center gap-2 rounded-2xl bg-emerald-50 px-4 py-3 text-sm font-semibold text-emerald-700 ring-1 ring-emerald-100">
          <CheckCircle2 className="h-4 w-4" /> Ingest complete — {result.locations} locations,{' '}
          {result.liveObservations} live observations ({result.sourceMode} mode).
        </p>
      )}
      {ingestError && (
        <p className="mt-4 flex items-center gap-2 rounded-2xl bg-red-50 px-4 py-3 text-sm font-semibold text-red-700 ring-1 ring-red-100">
          <AlertTriangle className="h-4 w-4" /> Ingest failed: {ingestError}
        </p>
      )}

      {loading && (
        <div className="mt-10 flex items-center justify-center text-slate-400">
          <Loader2 className="h-6 w-6 animate-spin" />
        </div>
      )}

      {error && !loading && (
        <div className="mt-4 rounded-2xl bg-red-50 px-4 py-3 text-sm font-semibold text-red-700 ring-1 ring-red-100">
          {error}
          <button onClick={refetch} className="ml-2 underline">Retry</button>
        </div>
      )}

      {data && (
        <>
          <div className="mt-4 grid grid-cols-2 gap-3 sm:grid-cols-4">
            <Stat label="Locations" value={data.locations} />
            <Stat label="Observations" value={data.observations.count} sub={`${data.observations.demoRows} simulated rows`} />
            <Stat label="Forecast rows" value={data.forecast.count} />
            <Stat label="AQI rows" value={data.aqi.count} sub={`${data.aqi.demoRows} simulated rows`} />
          </div>

          <section className="card mt-4 p-5">
            <h2 className="flex items-center gap-2 text-sm font-bold text-slate-900">
              <HardDrive className="h-4 w-4 text-slate-400" /> Coverage
            </h2>
            <dl className="mt-3 grid grid-cols-1 gap-3 text-sm sm:grid-cols-2">
              <div className="flex justify-between gap-4 rounded-xl bg-slate-50 px-3.5 py-2.5">
                <dt className="text-slate-400">Observations from</dt>
                <dd className="font-semibold text-slate-800">{fmtDate(data.observations.earliest)}</dd>
              </div>
              <div className="flex justify-between gap-4 rounded-xl bg-slate-50 px-3.5 py-2.5">
                <dt className="text-slate-400">Observations to</dt>
                <dd className="font-semibold text-slate-800">{fmtDate(data.observations.latest)}</dd>
              </div>
              <div className="flex justify-between gap-4 rounded-xl bg-slate-50 px-3.5 py-2.5">
                <dt className="text-slate-400">Forecast window</dt>
                <dd className="font-semibold text-slate-800">
                  {data.forecast.from ? `${data.forecast.from} → ${data.forecast.to}` : '—'}
                </dd>
              </div>
              <div className="flex justify-between gap-4 rounded-xl bg-slate-50 px-3.5 py-2.5">
                <dt className="text-slate-400">Any simulated data</dt>
                <dd className="font-semibold text-slate-800">{data.anyDemoData ? 'Yes' : 'No'}</dd>
              </div>
            </dl>
          </section>

          {Object.keys(data.meta || {}).length > 0 && (
            <section className="card mt-4 p-5">
              <h2 className="text-sm font-bold text-slate-900">Ingest metadata</h2>
              <div className="mt-3 space-y-1.5 text-sm">
                {Object.entries(data.meta).map(([k, v]) => (
                  <div key={k} className="flex justify-between gap-4 rounded-xl bg-slate-50 px-3.5 py-2">
                    <span className="text-slate-400">{k}</span>
                    <span className="font-semibold text-slate-800">{String(v)}</span>
                  </div>
                ))}
              </div>
            </section>
          )}
        </>
      )}
    </div>
  );
}
